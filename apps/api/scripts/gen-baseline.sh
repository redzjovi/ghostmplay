#!/usr/bin/env bash
# Regenerates db/migrations/000001_baseline.{up,down}.sql from db/schema.sql.
#
# The baseline is the whole schema in one version. It exists because the ten
# TypeORM migrations it replaces are a history, not a specification: they contain
# decisions that were later reversed (the `sold` boolean, the `citext` column,
# the `sync_jobs` table) and replaying them would mean re-deciding all of it.
#
# Generating the migration rather than hand-maintaining it means db/schema.sql
# (what sqlc reads) and the migration (what runs) cannot drift, which is the one
# failure mode here that would be silent: sqlc would type-check against columns
# that do not exist.
#
# FROZEN. 000001 is not to be regenerated again -- 000002 added a column to
# sync_state, and rewriting the baseline to include it would leave every already-
# migrated database permanently missing it, while a FRESH database would run
# 000001 (with the column) and then 000002 (adding it again) and fail on the
# duplicate. Both failures are worse than the drift this script prevents. Add a
# numbered migration instead: edit db/schema.sql so sqlc sees the change, and put
# the DDL in the new file.
set -euo pipefail

cd "$(dirname "$0")/.."

up="db/migrations/000001_baseline.up.sql"
down="db/migrations/000001_baseline.down.sql"

header() {
  cat <<'EOF'
-- Code generated by `make baseline`. DO NOT EDIT.
--
-- Source of truth: db/schema.sql. Edit that, then run `make baseline`.
--
-- This is the squashed end state of the ten TypeORM migrations that preceded
-- the Go rewrite. Adopting it on a database that already ran those ten is a
-- single `migrate force 1`, which records the version without executing
-- anything -- the schema it describes is already there.
EOF
}

{ header; echo; cat db/schema.sql; } > "$up"

# Seeds go in the same transaction as the DDL: a kind that has never completed a
# run still needs a row, because the UI reads one row per kind and the
# orchestrator upserts rather than inserts.
cat >> "$up" <<'EOF'

-- A kind that has never completed a run still needs a row: the sync panel reads
-- one row per kind, and the orchestrator upserts rather than inserts.
INSERT INTO sync_state (kind, mode)
VALUES ('marketplace', 'latest'), ('history', 'latest')
ON CONFLICT (kind) DO NOTHING;
EOF

{
  header
  cat <<'EOF'

-- Reverse order, so the drop order satisfies the foreign keys. sync_state is
-- dropped first because it references nothing, and the account tables go last
-- because sessions and identities both cascade from accounts anyway -- naming
-- them explicitly keeps the drop order readable rather than incidental.
DROP TABLE IF EXISTS sync_state;
DROP TABLE IF EXISTS account_identities;
DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS accounts;
DROP TABLE IF EXISTS marketplace_token_transfers;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS marketplace_favorites;
DROP TABLE IF EXISTS marketplace_item_detail;
DROP TABLE IF EXISTS marketplace_items;
EOF
} > "$down"

echo "wrote $up and $down"